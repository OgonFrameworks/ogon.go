// --- AGENT-016: AGENTS.md / CODEOWNERS generation ---

// AgentsMD is the canonical AGENTS.md content. Generated from the
// project's manifest so it stays in sync. Codifies the agent contract:
// safe tools only, dry-run enforced, explain contract honored.
type AgentsMD struct {
	ProjectName string
	Root        string
	Manifest    *Manifest
	GeneratedAt time.Time
}

// Render produces the AGENTS.md body.
func (a *AgentsMD) Render() string {
	var b strings.Builder
	fmt.Fprintf(&b, "# AGENTS.md — agent contract for %s\n\n", a.ProjectName)
	b.WriteString("## Agent surface\n")
	fmt.Fprintf(&b, "- agent surface version: %s\n", AgentSurfaceVersion)
	fmt.Fprintf(&b, "- manifest schema: %s\n", ManifestVersion)
	fmt.Fprintf(&b, "- MCP protocol: %s\n", "2024-11-05")
	b.WriteString("\n")
	b.WriteString("## Allowed tools\n")
	b.WriteString("- `ogon.explain` — stable, byte-stable explain output\n")
	b.WriteString("- `ogon.inspect` — read-only inspection of routes/models/config/runtime/modules\n")
	b.WriteString("- `ogon.gen` — deterministic codegen (dry-run enforced; never writes files)\n")
	b.WriteString("- `ogon.doctor` — environment diagnostics\n")
	b.WriteString("- `ogon.test` — affected test file listing (never executes tests)\n")
	b.WriteString("\n")
	b.WriteString("## Forbidden actions\n")
	b.WriteString("- Do not write to generated/ directly; regenerate via `ogon gen`.\n")
	b.WriteString("- Do not skip `ogon check` before commit.\n")
	b.WriteString("- Do not edit ogon.yaml without running `ogon doctor --fix`.\n")
	b.WriteString("\n")
	b.WriteString("## Pre-commit gate\n")
	b.WriteString("Run `ogon check` before every commit. The gate checks gofmt, generated\n")
	b.WriteString("freshness, manifest freshness, and ogon.yaml presence.\n")
	b.WriteString("\n")
	if a.Manifest != nil {
		b.WriteString("## Manifest summary\n")
		fmt.Fprintf(&b, "- routes: %d\n", len(a.Manifest.Routes))
		fmt.Fprintf(&b, "- models: %d\n", len(a.Manifest.Models))
		fmt.Fprintf(&b, "- modules: %d\n", len(a.Manifest.Modules))
		fmt.Fprintf(&b, "- skills: %d\n", len(a.Manifest.Skills))
		fmt.Fprintf(&b, "- path: .ogon/ogon.json\n")
		fmt.Fprintf(&b, "- refresh: `ogon agent validate --fix`\n")
	}
	b.WriteString("\n")
	b.WriteString("## Skills\n")
	b.WriteString("Per-task skills live under skills/ogongo/. See:\n")
	b.WriteString("- skills/ogongo/SKILL.md — top-level skill index\n")
	b.WriteString("- skills/ogongo/add-endpoint.md\n")
	b.WriteString("- skills/ogongo/add-model.md\n")
	b.WriteString("- skills/ogongo/add-job.md\n")
	b.WriteString("- skills/ogongo/fix-migration.md\n")
	return b.String()
}

// WriteAgentsMD writes AGENTS.md at the project root.
func WriteAgentsMD(root string, m *Manifest) (string, error) {
	if root == "" {
		return "", fmt.Errorf("agent: WriteAgentsMD needs root")
	}
	name := "ogon-app"
	if m != nil {
		name = m.Project.Name
	}
	a := &AgentsMD{
		ProjectName: name,
		Root:        root,
		Manifest:    m,
		GeneratedAt: time.Now().UTC(),
	}
	path := filepath.Join(root, "AGENTS.md")
	if err := os.WriteFile(path, []byte(a.Render()), 0o644); err != nil {
		return "", fmt.Errorf("agent: write AGENTS.md: %w", err)
	}
	return path, nil
}

// Codeowners generates the canonical CODEOWNERS file. By default every
// file is owned by the maintainers team. Module-contributed paths get
// an entry per the manifest's Modules list when present.
func Codeowners(root string, m *Manifest) (string, error) {
	if root == "" {
		return "", fmt.Errorf("agent: Codeowners needs root")
	}
	var b strings.Builder
	b.WriteString("# Codeowners — generated by `ogon agent codeowners`.\n")
	b.WriteString("# Edit AGENTS.md to change ownership policy; rerun the generator.\n")
	b.WriteString("* @ogonframeworks/maintainers\n")
	if m != nil {
		for _, mod := range m.Modules {
			fmt.Fprintf(&b, "/modules/%s/ @ogonframeworks/maintainers-%s\n",
				mod.Name, mod.Name)
		}
	}
	b.WriteString("\n")
	b.WriteString("# Generated files are owned by the generator.\n")
	b.WriteString("/generated/ @ogonframeworks/codegen-owners\n")
	return b.String(), nil
}

// WriteCodeowners writes CODEOWNERS at the project root.
func WriteCodeowners(root string, m *Manifest) (string, error) {
	body, err := Codeowners(root, m)
	if err != nil {
		return "", err
	}
	path := filepath.Join(root, ".github", "CODEOWNERS")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", fmt.Errorf("agent: mkdir .github: %w", err)
	}
	if err := os.WriteFile(path, []byte(body), 0o644); err != nil {
		return "", fmt.Errorf("agent: write CODEOWNERS: %w", err)
	}
	return path, nil
}

// --- AGENT-017: `ogon agent validate` ---

// ValidateReport is the output of `ogon agent validate`.
type ValidateReport struct {
	Fresh       bool   `json:"fresh"`
	Path        string `json:"path"`
	Reason      string `json:"reason,omitempty"`
	Fix         string `json:"fix,omitempty"`
	GeneratedAt string `json:"generated_at"`
}

// Validate checks the on-disk manifest against a freshly-regenerated
// copy and returns the freshness report. The check ignores the
// GeneratedAt timestamp (see manifestFresh).
//
// When fix=true the function regenerates the manifest in place. The
// caller (CLI) gates the write behind --yes in CI.
func Validate(root string, fix bool) (*ValidateReport, error) {
	if root == "" {
		return nil, fmt.Errorf("agent: Validate needs root")
	}
	path := ManifestPath(root)
	r := &ValidateReport{Path: path, GeneratedAt: time.Now().UTC().Format(time.RFC3339)}
	m, err := GenerateManifest(ManifestOptions{ProjectRoot: root, Now: time.Now().UTC()})
	if err != nil {
		r.Reason = "regenerate manifest: " + err.Error()
		r.Fix = "fix the manifest generator and rerun"
		return r, nil
	}
	existing, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			r.Reason = "manifest not on disk"
			r.Fix = "run `ogon agent dump --write` to generate"
			if fix {
				if _, err := WriteManifest(ManifestOptions{
					ProjectRoot: root,
					Now:         time.Now().UTC(),
				}); err != nil {
					return nil, err
				}
				r.Fresh = true
				r.Reason = "manifest created"
				r.Fix = ""
			}
			return r, nil
		}
		return nil, fmt.Errorf("agent: read manifest: %w", err)
	}
	fresh, err := manifestFresh(m, existing)
	if err != nil {
		r.Reason = "compare manifest: " + err.Error()
		return r, nil
	}
	r.Fresh = fresh
	if !fresh {
		r.Reason = "manifest is stale"
		r.Fix = "run `ogon agent validate --fix` to refresh"
		if fix {
			if _, err := WriteManifest(ManifestOptions{
				ProjectRoot: root,
				Now:         time.Now().UTC(),
			}); err != nil {
				return nil, err
			}
			r.Fresh = true
			r.Reason = "manifest refreshed"
			r.Fix = ""
		}
	}
	return r, nil
}

// --- AGENT-018: structured logs for agents ---

// AgentLog is the canonical structured-log entry for agent events.
// Every field is typed so an agent can parse logs with confidence.
type AgentLog struct {
	Type         string            `json:"type"` // tool_call|tool_result|plan|commit|error
	Tool         string            `json:"tool,omitempty"`
	Args         map[string]string `json:"args,omitempty"`
	Result       string            `json:"result,omitempty"`
	ExitCode     int               `json:"exit_code,omitempty"`
	Error        string            `json:"error,omitempty"`
	Timestamp    string            `json:"timestamp"`
	AgentSurface string            `json:"agent_surface"`
}

// EmitLog writes a single agent-log line to w. The line is
// JSON-encoded and \n-terminated. The timestamp is UTC RFC3339.
func EmitLog(w interface{ Write([]byte) (int, error) }, l AgentLog) error {
	if l.Timestamp == "" {
		l.Timestamp = time.Now().UTC().Format(time.RFC3339)
	}
	if l.AgentSurface == "" {
		l.AgentSurface = AgentSurfaceVersion
	}
	body, err := jsonMarshalLine(l)
	if err != nil {
		return fmt.Errorf("agent: marshal log: %w", err)
	}
	if _, err := w.Write(append(body, '\n')); err != nil {
		return fmt.Errorf("agent: write log: %w", err)
	}
	return nil
}

// jsonMarshalLine is a thin wrapper so we keep one encoding/json
// call site in agmd.go.
func jsonMarshalLine(l AgentLog) ([]byte, error) {
	return jsonMarshal(l)
}

// --- AGENT-019: `ogon dev --agent` no-browser policy ---

// DevAgentPolicy codifies what `ogon dev --agent` does and does NOT do:
//   - does NOT open a browser
//   - prints the dev server URL to stdout as JSON
//   - emits structured logs to stderr
//   - never auto-prompts for input
//
// The policy is a value type so tests can assert on each field.
type DevAgentPolicy struct {
	OpenBrowser    bool   `json:"open_browser"`    // always false under --agent
	PrintURLJSON   bool   `json:"print_url_json"`  // always true under --agent
	StructuredLogs bool   `json:"structured_logs"` // always true under --agent
	Interactive    bool   `json:"interactive"`     // always false under --agent
	URL            string `json:"url,omitempty"`
}

// DevAgentPolicyFor returns the canonical policy for `ogon dev --agent`.
// The URL is filled by the CLI's dev loop when it picks a port.
func DevAgentPolicyFor(url string) DevAgentPolicy {
	return DevAgentPolicy{
		OpenBrowser:    false,
		PrintURLJSON:   true,
		StructuredLogs: true,
		Interactive:    false,
		URL:            url,
	}
}

