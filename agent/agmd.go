// Inspect returns a stable text + structured payload for the named
// inspect topic. The topic set is identical to `ogon inspect <what>`
// at the CLI: routes|models|config|runtime|modules.
func Inspect(what string) (string, map[string]any, error) {
	switch what {
	case "routes", "models", "config", "runtime", "modules":
	default:
		return "", nil, fmt.Errorf("agent: Inspect unknown topic %q", what)
	}
	root := detectProjectRoot()
	m, err := LoadManifest(root)
	if err != nil {
		// No manifest on disk: return a stable synthetic payload so
		// agents always get a parseable response. The footer marks
		// synthetic output so agents can detect missing manifests.
		body := fmt.Sprintf("# ogon inspect %s\n(no manifest; run `ogon agent dump --write`)\n", what)
		return body, map[string]any{
			"topic":     what,
			"items":     []any{},
			"synthetic": true,
		}, nil
	}
	switch what {
	case "routes":
		var b strings.Builder
		fmt.Fprintf(&b, "# ogon inspect routes\n")
		for _, r := range m.Routes {
			fmt.Fprintf(&b, "%s\t%s\t%s\t%s\n", r.Method, r.Path, r.Handler, r.Auth)
		}
		return b.String(), map[string]any{
			"topic": "routes",
			"items": m.Routes,
		}, nil
	case "models":
		var b strings.Builder
		fmt.Fprintf(&b, "# ogon inspect models\n")
		for _, mm := range m.Models {
			fmt.Fprintf(&b, "%s\t%s\t%d fields\n", mm.Name, mm.Table, len(mm.Fields))
		}
		return b.String(), map[string]any{
			"topic": "models",
			"items": m.Models,
		}, nil
	case "config":
		var b strings.Builder
		fmt.Fprintf(&b, "# ogon inspect config\n")
		for _, k := range m.ConfigSchema {
			fmt.Fprintf(&b, "%s\t%s\t%s\n", k.Key, k.Type, k.Default)
		}
		return b.String(), map[string]any{
			"topic": "config",
			"items": m.ConfigSchema,
		}, nil
	case "runtime":
		var b strings.Builder
		fmt.Fprintf(&b, "# ogon inspect runtime\n")
		fmt.Fprintf(&b, "framework: %s\n", m.Framework)
		fmt.Fprintf(&b, "go: %s\n", m.GoVersion)
		fmt.Fprintf(&b, "os/arch: %s/%s\n", m.OS, m.Arch)
		fmt.Fprintf(&b, "goroutines (current): %d\n", runtime.NumGoroutine())
		return b.String(), map[string]any{
			"topic":     "runtime",
			"framework": m.Framework,
			"go":        m.GoVersion,
			"os":        m.OS,
			"arch":      m.Arch,
		}, nil
	case "modules":
		var b strings.Builder
		fmt.Fprintf(&b, "# ogon inspect modules\n")
		for _, mm := range m.Modules {
			fmt.Fprintf(&b, "%s\t%s\n", mm.Name, mm.Version)
		}
		return b.String(), map[string]any{
			"topic": "modules",
			"items": m.Modules,
		}, nil
	}
	return "", nil, fmt.Errorf("agent: Inspect unreachable")
}

