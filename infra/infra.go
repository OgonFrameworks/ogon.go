// Envs returns the three standard environments (local/dev/prod) (INFRA-026).
func (c *InfraConfig) Envs() []string { return []string{"local", "dev", "prod"} }

// Validate returns nil if the config is internally consistent. The CLI calls
// this before any generator runs so misconfigurations surface as OGON-K
// diagnostics rather than malformed artifacts.
func (c *InfraConfig) Validate() error {
	if c.App.Name == "" {
		return fmt.Errorf("infra: app.name is required (INFRA-001)")
	}
	if c.App.Port == 0 {
		return fmt.Errorf("infra: app.port is required")
	}
	if c.Cloud != "" {
		switch c.Cloud {
		case "aws", "gcp", "azure":
		default:
			return fmt.Errorf("infra: cloud %q is not aws|gcp|azure", c.Cloud)
		}
	}
	if c.Env != "" {
		switch c.Env {
		case "local", "dev", "prod":
		default:
			return fmt.Errorf("infra: env %q is not local|dev|prod", c.Env)
		}
	}
	return nil
}

