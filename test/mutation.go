// MutationGuide is the markdown content for TEST-041.
const MutationGuide = `# Mutation testing guide (TEST-041)

## What it is

Mutation testing rewrites the production code in small ways ("mutants") and
checks whether the test suite catches the change. A surviving mutant is a
hole in coverage: code that the tests do not actually exercise meaningfully.

## How to run

	ogon test mutation --base main --diff HEAD

The command wraps ` + "`gremlins go`" + ` (or the engine configured in
` + "`ogon.yaml -> testing -> mutation_engine`" + `) and emits a JSON report
under testdata/mutation/.

## Interpreting results

A mutant survival rate above 5% indicates one of three problems:

  1. The test for that line is missing or asserts nothing meaningful.
  2. The line is defensive code that should not exist (delete the line).
  3. The mutant is equivalent (the engine cannot tell that two expressions
     produce the same output for all inputs). Equivalent mutants are
     unfixable; flag them in the report so future runs ignore them.

## What NOT to do

Do not write tests just to kill mutants. Tests exist to document behaviour
and catch regressions. A mutant that survives because the tests check the
right thing is fine; that mutant is equivalent.

## The law

The test infrastructure law from Part XIV applies: writing mutation tests
must not exceed the behaviour under test. If a mutant survives, fix the
production code or delete it. Never add a test whose only purpose is to
kill a mutant.
`

